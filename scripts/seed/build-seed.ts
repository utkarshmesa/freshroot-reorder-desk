// Generates supabase/seed.sql (local) and supabase/bootstrap.sql (hosted projects) from lib/rules/defaults.ts,
// so the seed and the code never disagree.
// Run: node --experimental-strip-types scripts/seed/build-seed.ts
import { writeFileSync } from "node:fs";
import { DEFAULT_REASON_CODES, DEFAULT_RULES } from "../../lib/rules/defaults.ts";

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;

import { LOCAL_TEST_PASSWORD, LOCAL_USERS as users } from "./users.ts";

const RULES_REASON = "Initial rules: Raghav's documented rules + BUILD_PLAN v1.2 defaults";

/** Rows every environment needs: shadow mode, rules v1, reason codes. No users, no test data. */
const startRows = (rulesInsert: string) => `insert into public.app_mode (id, mode) values (true, 'shadow') on conflict (id) do nothing;
insert into public.app_setting (id) values (true) on conflict (id) do nothing;

${rulesInsert}

insert into public.reason_code (code, label, sort) values
${DEFAULT_REASON_CODES.map((r, i) => `  (${q(r.code)}, ${q(r.label)}, ${i})`).join(",\n")}
on conflict (code) do nothing;
`;

const sql = `-- GENERATED by scripts/seed/build-seed.ts. Do not edit by hand.
-- Applied by \`npx supabase db reset\` (local only).

${startRows(`insert into public.rule_version (params, reason, is_current)
values (${q(JSON.stringify(DEFAULT_RULES))}::jsonb, ${q(RULES_REASON)}, true);`)}
-- Local test users (password in scripts/seed/build-seed.ts, local only).
${users
  .map(
    (u) => `insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at, created_at, updated_at,
  raw_app_meta_data, raw_user_meta_data, confirmation_token, recovery_token, email_change_token_new, email_change)
values ('00000000-0000-0000-0000-000000000000', ${q(u.id)}, 'authenticated', 'authenticated', ${q(u.email)},
  crypt(${q(LOCAL_TEST_PASSWORD)}, gen_salt('bf')), now(), now(), now(),
  '{"provider":"email","providers":["email"]}', '{}', '', '', '', '');
insert into auth.identities (id, user_id, provider_id, identity_data, provider, last_sign_in_at, created_at, updated_at)
values (gen_random_uuid(), ${q(u.id)}, ${q(u.id)}, jsonb_build_object('sub', ${q(u.id)}, 'email', ${q(u.email)}), 'email', now(), now(), now());
insert into public.app_user (user_id, name, email, roles, is_owner)
values (${q(u.id)}, ${q(u.name)}, ${q(u.email)}, array[${u.roles.map(q).join(", ")}]::text[], ${u.owner});`,
  )
  .join("\n\n")}
`;

// Hosted projects (production): run once in the SQL editor after the migrations (docs/DEPLOY_CHECKLIST.md).
// Rules v1 goes in only if no rule version exists, so running it twice never adds a second current version.
const bootstrap = `-- GENERATED by scripts/seed/build-seed.ts. Do not edit by hand.
-- Hosted projects (production): run ONCE in the Supabase SQL editor after \`supabase db push\`.
-- No users and no test data. People are added as in docs/DEPLOY_CHECKLIST.md.

${startRows(`insert into public.rule_version (params, reason, is_current)
select ${q(JSON.stringify(DEFAULT_RULES))}::jsonb, ${q(RULES_REASON)}, true
where not exists (select 1 from public.rule_version);`)}`;

writeFileSync(new URL("../../supabase/seed.sql", import.meta.url), sql);
writeFileSync(new URL("../../supabase/bootstrap.sql", import.meta.url), bootstrap);
console.log("wrote supabase/seed.sql and supabase/bootstrap.sql");
